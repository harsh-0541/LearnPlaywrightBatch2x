// Declare a variable and print it
let z = 10;
console.log("The value of z is: " + z);

// Function to add two numbers
function add(num1, num2) {
    return num1 + num2;
}

// Function to multiply two numbers
function multiply(num1, num2) {
    return num1 * num2;
}

// Define two numbers
let number1 = 5;
let number2 = 3;

// Perform addition and multiplication
let sum = add(number1, number2);
let product = multiply(number1, number2);

// Display results
console.log(`Addition of ${number1} and ${number2} is: ${sum}`);
console.log(`Multiplication of ${number1} and ${number2} is: ${product}`);
